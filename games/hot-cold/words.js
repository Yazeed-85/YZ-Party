// اختيار كلمتين وتصنيفين مختلفين للاعبَين مع عدم تكرار الكلمات السابقة
export function pickWordsPair(usedWords = []) {
  const usedSet = new Set(usedWords);
  const allCats = Object.keys(WORDS_DB);
  const cat1 = allCats[(Math.random() * allCats.length) | 0];
  const otherCats = allCats.filter(c => c !== cat1);
  const cat2 = Math.random() > 0.15 && otherCats.length
    ? otherCats[(Math.random() * otherCats.length) | 0]
    : allCats[(Math.random() * allCats.length) | 0];

  const pickFrom = (cat, avoidWord) => {
    const pool = WORDS_DB[cat].filter(w => !usedSet.has(w) && w !== avoidWord);
    const list = pool.length ? pool : WORDS_DB[cat].filter(w => w !== avoidWord);
    return list[(Math.random() * list.length) | 0];
  };

  const w1 = pickFrom(cat1, '');
  const w2 = pickFrom(cat2, w1);
  return { words: [w1, w2], cats: [cat1, cat2] };
}